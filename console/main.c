#include "io.h"
#include "mySimpleComputer.h"
#include <stdio.h>

int main()
{
    // a. инициализировать оперативную память, аккумулятор, счетчик команд и
    // регистр флагов;
    printf("\n16.a. Инициализация памяти, аккумулятора, счетчика команд и "
           "регистра флагов...\n");
    sc_memoryInit(); // Инициализация оперативной памяти
    sc_regInit(); // Инициализация регистра флагов
    sc_accumulatorInit(); // Инициализация аккумулятора
    sc_icounterInit(); // Инициализация счетчика команд
    printf("   Инициализация выполнена.\n");

    // b. установить произвольному количеству произвольных ячеек оперативной
    // памяти произвольные значения. Вывести содержимое оперативной памяти (в
    // декодированном формате по 10 ячеек в строке через пробел);
    printf("\n16.b. Установка значений памяти и вывод содержимого (по 10 ячеек "
           "в строке)...\n");
    sc_memorySet(10, 12345); // Запись значения в ячейку памяти 10
    sc_memorySet(20, -500); // Запись отрицательного значения
    sc_memorySet(50, 0); // Запись нуля
    sc_memorySet(127, 16383); // Запись максимального 15-битного значения
    printf("   Установлены значения для ячеек 10, 20, 50, 127.\n");
    printf("   Содержимое памяти (декодированный формат):\n");
    for (int i = 0; i < MEMORY_SIZE; ++i) {
        io_printCell(i);
        if ((i + 1) % 10 == 0) {
            printf("\n");
        }
    }

    // c. попробовать задать какой-нибудь ячейке оперативной памяти недопустимое
    // значение и вывести статус завершения соответствующей функции;
    printf("\n16.c. Попытка задать недопустимое значение памяти (адрес 128 - "
           "вне границ, значение 40000 - вне 15-битного диапазона):\n");
    int set_mem_status = sc_memorySet(128, 40000);
    printf("   Статус sc_memorySet (ожидается -1): %d\n", set_mem_status);

    // d. установить произвольные значения флагов и вывести содержимое регистра
    // флагов.
    printf("\n16.d. Установка произвольных значений флагов и вывод регистра "
           "флагов...\n");
    sc_regSet(FLAG_OVERFLOW, 1);
    sc_regSet(FLAG_DIVISION_BY_ZERO, 1);
    sc_regSet(FLAG_MEMORY_ERROR, 0);
    printf("   Флаги OVERFLOW, DIVISION_BY_ZERO установлены, MEMORY_ERROR "
           "сброшен.\n");
    printf("   Состояние регистра флагов:\n");
    io_printFlags();

    // e. попробовать установить некорректное значение флага. Вывести статус
    // завершения функции.
    printf("\n16.e. Попытка задать некорректное значение флага (регистр 10 - "
           "не существует):\n");
    int set_reg_status = sc_regSet(10, 1);
    printf("   Статус sc_regSet (ожидается -1): %d\n", set_reg_status);

    // f. установить значение аккумулятора и вывести его на экран.
    printf("\n16.f. Установка значения аккумулятора и вывод на экран...\n");
    sc_accumulatorSet(9876);
    printf("   Аккумулятор установлен в 9876.\n");
    io_printAccumulator();

    // g. попробовать задать аккумулятору недопустимое значение и вывести статус
    // завершения функции;
    printf("\n16.g. Попытка задать недопустимое значение аккумулятора (40000 - "
           "вне 15-битного диапазона):\n");
    int set_acc_status = sc_accumulatorSet(40000);
    printf("   Статус sc_accumulatorSet (ожидается -1): %d\n", set_acc_status);

    // h. установить значение счетчика команд и вывести его на экран.
    printf("\n16.h. Установка значения счетчика команд и вывод на экран...\n");
    sc_icounterSet(64);
    printf("   Счетчик команд установлен в 64.\n");
    io_printCounters();

    // i. попробовать задать счетчику команд недопустимое значение и вывести
    // статус завершения функции;
    printf("\n16.i. Попытка задать недопустимое значение счетчика команд (-1 - "
           "вне допустимого диапазона адресов):\n");
    int set_ic_status = sc_icounterSet(-1);
    printf("   Статус sc_icounterSet (ожидается -1): %d\n", set_ic_status);

    // j. декодировать значение произвольной ячейки памяти и значение
    // аккумулятора;
    printf("\n16.j. Декодирование значения ячейки памяти 20 и "
           "аккумулятора...\n");
    printf("   Декодирование значения ячейки памяти 20 (%d):\n", memory[20]);
    io_printDecodedCommand(memory[20]);
    printf("   Декодирование значения аккумулятора (%d):\n", accumulator);
    io_printDecodedCommand(accumulator);

    // k. закодировать команду (любую допустимую из системы команд) и вывести
    // полученное значение в разных системах счисления.
    printf("\n16.k. Кодирование команды LOAD 20 (код операции 0x14, операнд "
           "20) и вывод...\n");
    int encoded_command;
    if (sc_commandEncode(0, 0x14, 20, &encoded_command) == 0) {
        printf("   Команда LOAD 20 успешно закодирована.\n");
        printf("   Закодированная команда: ");
        io_printDecodedCommand(encoded_command);
    } else {
        printf("   Ошибка кодирования команды\n");
    }
    return 0;
}